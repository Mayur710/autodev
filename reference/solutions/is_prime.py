"""Reference solution — human-written, used ONLY to validate the oracle
tests (validate_oracle.py). Never imported by the oracle suite itself."""


def is_prime(n: int) -> bool:
    if n <= 1:
        return False
    if n <= 3:
        return True
    if n % 2 == 0:
        return False
    i = 3
    while i * i <= n:
        if n % i == 0:
            return False
        i += 2
    return True
